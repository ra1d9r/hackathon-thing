-- 0035 — фаза 11: указатели под запросы учительской части.
--
-- Новых таблиц нет: классы, рассылки и чат заведены ещё в 0009, RLS и
-- публикация Realtime — в 0012 и 0013. Здесь только указатели под три
-- запроса, которые появились вместе с эндпоинтами и без них шли бы
-- последовательным чтением.

-- ─── Видимость файла ─────────────────────────────────────────────────────────

-- `GET /v1/files/:id/url` проверяет, присылали ли ученику материал с этим
-- файлом, — то есть идёт от файла к материалу. Обратного пути указателя
-- не было, и проверка читала бы всю таблицу материалов на каждую выдачу
-- ссылки.
create index if not exists materials_file_idx
  on public.materials(file_id)
  where file_id is not null;

-- ─── Непрочитанные входящие ──────────────────────────────────────────────────

-- Счётчик непрочитанного считается на каждом открытии входящих и на каждой
-- отметке о просмотре. Частичный указатель здесь выгоден вдвойне: непрочитанных
-- у ученика единицы, а прочитанных со временем становятся сотни.
create index if not exists distribution_receipts_unread_idx
  on public.distribution_receipts(student_id)
  where seen_at is null;

-- ─── Список классов учителя ──────────────────────────────────────────────────

-- Прежний указатель был частичным (`where not is_archived`), а список классов
-- показывает и архивные — они просто идут после действующих. Полный указатель
-- покрывает оба случая; отдельный частичный после этого не нужен.
drop index if exists public.classes_teacher_idx;

create index if not exists classes_teacher_idx
  on public.classes(teacher_id, is_archived, created_at desc);
