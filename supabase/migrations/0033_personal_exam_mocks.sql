-- 0033 — пробник становится персональным.
--
-- До фазы 9 пробник лежал готовым тестом, общим для всех: одна запись
-- `assessments` со `student_id = null`. Это работало, пока пробник был один
-- на экзамен.
--
-- Но ЕНТ сдают парами профильных предметов, и утверждённых пар четыре.
-- Общий пробник для всех означал бы либо четыре почти одинаковых теста,
-- отличающихся только профильными секциями (и повторяющих обязательные
-- секции четырежды), либо один тест с чужими предметами. Поэтому пробник
-- теперь **собирается** из банка под выбор конкретного ученика
-- (04-domain-logic.md, §6.4), а значит принадлежит ему.
--
-- Прежние общие пробники из наполнения остаются рабочими: ограничение
-- допускает обе формы.

alter table public.assessments
  drop constraint assessments_personal;

alter table public.assessments
  add constraint assessments_personal check (
    -- Пробник бывает и общим (заготовка из наполнения), и собранным
    -- под ученика. Обе формы законны.
    kind = 'exam_mock'
    -- Диагностика, задача и проверка знаний персональны всегда:
    -- их состав подобран под конкретного ученика.
    or (kind in ('diagnostic','ai_task','knowledge_check') and student_id is not null)
  );

comment on column public.assessments.student_id is
  'Владелец персонального теста. У пробника из наполнения пуст, у собранного — ученик.';

-- Собранные пробники ищутся по паре «ученик + экзамен»: так находится
-- незавершённая попытка и история прошлых.
create index if not exists assessments_student_exam_idx
  on public.assessments(student_id, exam_profile_id)
  where kind = 'exam_mock' and student_id is not null;
